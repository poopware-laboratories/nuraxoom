# gen-wlr-fp.sh MESA_SRC OPENTEGRA_SRC   (Linux; needs gcc, flex, bison)
# Assembles the wlroots fragment programs of the grate patches (src/gallium/
# drivers/grate/fp/wlr/*.asm in a patched MESA_SRC) with xf86-video-
# opentegra's shader assembler and writes fp/wlr/wlr_programs.h there.
set -euo pipefail
M=$(cd "$1" && pwd) O=$(cd "$2" && pwd)
ASM=$O/src/gpu/gr3d-asm
WLR=$M/src/gallium/drivers/grate/fp/wlr
VS=$O/src/exa/shaders/vertex_common.asm
W=$(mktemp -d)
trap 'rm -rf "$W"' EXIT

cd "$W"
for g in vertex_asm linker_asm fragment_asm; do
	flex -P $g --nounput -o $g.lex.c $ASM/$g.l
	bison -p $g -b $g -d -o $g.tab.c $ASM/$g.y
done
gcc -O1 -I$ASM -I. -o gen_shader_bin \
	$O/src/exa/gen_shader_bin.c *.lex.c *.tab.c

out=$WLR/wlr_programs.h
{
	echo "/* Generated by NuraXoom's packages/mesa-grate/gen-wlr-fp.sh from fp/wlr */"
	echo
} > $out
for p in solid:link_solid solid_over:link_solid tex:link_tex tex_over:link_tex \
	 tex_rgbx:link_tex tex_rgbx_over:link_tex; do
	fs=${p%%:*} lnk=${p##*:}
	./gen_shader_bin --vs $VS --lnk $WLR/$lnk.asm --fs $WLR/$fs.asm \
		--fpname wlr_$fs --vpname unused --lpname wlr_$lnk --out $fs.h
	# keep the Tegra20 fragment words, the linker words and the program
	# parameters; drop the T114 copy and opentegra's vertex program
	awk '
		/^#ifndef fp_.*_t114_def/ { skip = 1 }
		/^#ifndef vp_/ { skip = 1 }
		/^#ifndef (fp_|lp_|prog_)/ && !/_t114_def/ { skip = 0 }
		!skip && !/^#include/ && !/Autogenerated/
		/^#endif/ { skip = 0 }
	' $fs.h | sed -e '/fs_prog_words_t114/d' -e '/vs_prog_words/d' \
		-e '/vs_attrs_/d' >> $out
done
echo "wrote $out"
